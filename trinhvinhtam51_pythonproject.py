#1. Tạo Frame
import pandas as pd
data = {
  "Họ và Tên": [
    "Trịnh Vinh Tâm","Phan Lê Vy Thanh",
    "Lê Dương Bảo Lâm","Kiều Minh Tuấn",
    "Lâm Vĩ Dạ","Alexander",
    "Trịnh Trần Phương Tuấn","Ngô Kiến Huy",
    "Bray","Trần Minh Hiếu"
    ],
  "điểm chuyên cần" : [10,9,8,10,10,4,7,6,8,9],
  "điểm giữa kì" : [9,9,8,3,10,9,7,9,10,10],
  "điểm cuối kì" : [9,10,8,8,9,1,9,10,7,9]
}
df = pd.DataFrame(data)
df.index =range(1,11)
print(df)



#2. Tính điểm tổng kết:
df["điểm tổng kết"] = 0.2 * df['điểm chuyên cần'] + 0.3 * df['điểm giữa kì'] + 0.5 * df['điểm cuối kì']
display (df)

#3. Xếp loại sinh viên
def Xep_loai(diem_tong_ket):
  if diem_tong_ket >= 8.5:
    return "Giỏi"
  elif diem_tong_ket >= 7.0:
    return "khá"
  elif diem_tong_ket >= 5:
    return "Trung Bình"
  else:
    return "Yếu"
df["Xếp loại sinh viên"] = df["điểm tổng kết"].apply(Xep_loai)
display(df)

#4. Thống kê
diem_tb = df["điểm tổng kết"].mean()
print("điểm tổng kết trung bình",round(diem_tb,2))
diem_cao_nhat = df["điểm tổng kết"].max()
ds_cao_nhat = df[df["điểm tổng kết"] == diem_cao_nhat]
print("Sinh viên có điểm cao nhất:",
      ", ".join(ds_cao_nhat["Họ và Tên"]))
diem_thap_nhat = df["điểm tổng kết"].min()
ds_thap_nhat = df[df["điểm tổng kết"] == diem_thap_nhat]
print("Sinh viên có điểm thấp nhất:",
      ", ".join(ds_thap_nhat["Họ và Tên"]))
so_sv_dat = (df["điểm tổng kết"] >= 5).sum()
print("Số sinh viên đạt:", so_sv_dat)

#5. Sử dụng matpotlip
import matplotlib.pyplot as plt
plt.barh(df["Họ và Tên"], df["điểm tổng kết"])
plt.title("Điểm tổng kết của 10 sinh viên")
plt.xlabel("Điểm tổng kết")
plt.ylabel("Tên sinh viên")
plt.xlim(0, 10)
plt.tight_layout()
plt.show()
